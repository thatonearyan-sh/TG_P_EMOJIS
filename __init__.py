_EMOJI_REGEX = re.compile(
    "|".join(re.escape(k) for k in sorted(MESSAGE_EMOJI_IDS.keys(), key=len, reverse=True))
) if MESSAGE_EMOJI_IDS else None

_EMOJI_PREFIX_REGEX = re.compile(r'^[^\w\s]+')


def premiumize_text(text: str) -> str:
    """
    Scans any input message text and upgrades standard unicode emojis to their
    Telegram custom animated sticker equivalents (<tg-emoji>).
    
    Supports '<raw>...</raw>' protection tags to preserve raw unicode emojis.
    """
    if not _EMOJI_REGEX or not text:
        return text

    # Extract and protect <raw> blocks
    raw_blocks: list[str] = []
    def save_raw(m):
        raw_blocks.append(m.group(1))
        return f"__RAW_BLOCK_{len(raw_blocks) - 1}__"

    protected_text = re.sub(r'<raw>(.*?)</raw>', save_raw, text, flags=re.DOTALL)

    # Process emojis on unprotected text
    def repl(m):
        ch = m.group(0)
        eid = MESSAGE_EMOJI_IDS.get(ch)
        return f'<tg-emoji emoji-id="{eid}">{ch}</tg-emoji>' if eid else ch

    result = _EMOJI_REGEX.sub(repl, protected_text)

    # Restore raw blocks
    for idx, content in enumerate(raw_blocks):
        result = result.replace(f"__RAW_BLOCK_{idx}__", content)

    return result


def get_custom_emoji_id(identifier: str) -> Optional[str]:
    """
    Returns the Telegram custom emoji ID for either a Unicode emoji (e.g. '💎')
    or a named icon key (e.g. 'CHERRY_BOMB', 'PIXEL_DIAMOND', 'TBOI_DICE_D6').
    """
    if identifier in MESSAGE_EMOJI_IDS:
        return MESSAGE_EMOJI_IDS[identifier]
    upper_id = identifier.upper()
    if upper_id in EMOJI_ICONS:
        return EMOJI_ICONS[upper_id]
    return None


def custom_tag(symbol_or_name: str, fallback: str = "🔥") -> str:
    """
    Generates a single <tg-emoji emoji-id="..."> HTML tag for use in messages.
    """
    eid = get_custom_emoji_id(symbol_or_name)
    if not eid:
        # Check if identifier is already numeric emoji-id
        if symbol_or_name.isdigit():
            eid = symbol_or_name
        else:
            return fallback or symbol_or_name
    return f'<tg-emoji emoji-id="{eid}">{fallback}</tg-emoji>'


def styled_btn(
    text: str,
    callback_data: Optional[str] = None,
    url: Optional[str] = None,
    web_app_url: Optional[str] = None,
    style: str = "primary",
    icon: Optional[str] = None,
    icon_id: Optional[str] = None
) -> InlineKeyboardButton:
    """
    Creates an ultra-luxury modern Telegram button equipped with native animated
    custom sticker icon (icon_custom_emoji_id) and visual style colors.
    
    Automatically strips leading unicode emojis from the button label if an animated
    icon is supplied to prevent clumsy double-emoji rendering.
    """
    chosen_icon_id = icon_id
    if not chosen_icon_id and icon:
        chosen_icon_id = get_custom_emoji_id(icon)

    clean_text = text
    if chosen_icon_id:
        clean_text = _EMOJI_PREFIX_REGEX.sub("", text).strip() or text

    kwargs = {"text": clean_text}
    if callback_data:
        kwargs["callback_data"] = callback_data
    if web_app_url:
        kwargs["web_app"] = WebAppInfo(url=web_app_url)
    elif url:
        kwargs["url"] = url
    if chosen_icon_id:
        kwargs["icon_custom_emoji_id"] = str(chosen_icon_id)
    if style:
        kwargs["style"] = style

    return InlineKeyboardButton(**kwargs)
